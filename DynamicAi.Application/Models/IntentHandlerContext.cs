using DynamicAi.Application.Models.DirectIntegration;

namespace DynamicAi.Application.Models;


/// <summary>
/// Context information passed to intent handlers.
/// Contains previous conversation state and execution metadata.
/// </summary>
public class IntentHandlerContext
{
    /// <summary>
    /// Previous question in the conversation (for follow-ups).
    /// </summary>
    public string? PreviousQuestion { get; init; }

    /// <summary>
    /// Previously generated SQL (for refinements).
    /// </summary>
    public string? PreviousSql { get; init; }

    /// <summary>
    /// Query log ID for tracking.
    /// </summary>
    public Guid? QueryLogId { get; init; }

    /// <summary>
    /// Tenant identifier for multi-tenancy.
    /// </summary>
    public string? TenantId { get; init; }

    /// <summary>
    /// Company ID for data isolation.
    /// </summary>
    public int? CompanyId { get; init; }

    /// <summary>
    /// Session ID for conversation context tracking.
    /// Used by PredictIntentHandler to retrieve previous query results.
    /// </summary>
    public string? SessionId { get; init; }

    /// <summary>
    /// The PageID associated with the previous turn's RAG context.
    /// Used to detect scope shifts and prevent invalid SQL wrapping.
    /// </summary>
    public int? PreviousPageId { get; init; }

    /// <summary>
    /// Precomputed condenser result from parallel execution in Orchestrator.
    /// When set, handlers should use this instead of calling the condenser service again.
    /// </summary>
    public CondenserResult? PrecomputedCondenserResult { get; init; }

    /// <summary>
    /// Recent conversation history (for condenser bypass / inline detection)
    /// </summary>
    public List<DynamicAi.Domain.Entities.ConversationTurn>? ConversationHistory { get; init; }

    /// <summary>
    /// Flag indicating whether the condenser was bypassed (triggers inline context detection)
    /// </summary>
    public bool IsCondenserBypassed { get; init; }

    /// <summary>
    /// Precomputed query embedding generated by orchestrator. Used to avoid duplicate calls to embedding services in Handlers.
    /// </summary>
    public float[]? PrecomputedEmbedding { get; init; }

    /// <summary>
    /// The explicit PageId passed directly by the user from the UI Dropdown.
    /// When set, bypasses the semantic search in RAG.
    /// </summary>
    public int? ExplicitPageId { get; init; }

    /// <summary>
    /// Pre-generated SQL retrieved from the Query Cache (if available).
    /// </summary>
    public string? CachedSql { get; init; }

    /// <summary>
    /// The PageID associated with the cached SQL query.
    /// </summary>
    public int? CachedPageId { get; init; }

    /// <summary>
    /// The original LLM Intent (e.g. DataRetrieval, PredictionWithDataRetrieval) retrieved from the query cache.
    /// </summary>
    public string? CachedIntent { get; init; }

    /// <summary>
    /// The unique identifier of the cache record in the vector database.
    /// </summary>
    public string? CachedCacheId { get; init; }

    /// <summary>
    /// 🚀 [DIRECT INTEGRATION] The pre-resolved page context (Schema, Master, Details) 
    /// injected directly from the ERP. When set, handlers must bypass RAG and use this context.
    /// </summary>
    public ShippedPageContext? InjectedContext { get; init; }

    /// <summary>
    /// Target database connection string provided by the caller.
    /// </summary>
    public string? ConnectionString { get; init; }
}
